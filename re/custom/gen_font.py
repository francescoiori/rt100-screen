"""Render ASCII 32..126 into an 8x16 1-bpp font for the screen patch.

Output font8x16.h: font8x16[95][8], one uint16 per column, bit y = row y
(bit 0 at the top), matching the display's column-by-column pixel order.
Also writes font_preview.png.
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
W, H, SIZE = 8, 16, 13


def main():
    font = ImageFont.truetype(TTF, SIZE)
    ascent, _ = font.getmetrics()
    rows, glyphs = [], []
    for c in range(32, 127):
        img = Image.new("L", (W, H), 0)
        d = ImageDraw.Draw(img)
        left = (W - font.getlength(chr(c))) / 2
        d.text((left, (H - SIZE) // 2 + 12 - ascent), chr(c), font=font, fill=255)
        px = img.load()
        cols = [sum(1 << y for y in range(H) if px[x, y] >= 110) for x in range(W)]
        glyphs.append(cols)
        rows.append(img.point(lambda v: 255 if v >= 110 else 0))

    out = os.path.join(HERE, "font8x16.h")
    with open(out, "w") as f:
        f.write("/* Generated by gen_font.py from DejaVu Sans Mono Bold. */\n")
        f.write("static const unsigned short font8x16[95][8] = {\n")
        for c, cols in zip(range(32, 127), glyphs):
            ch = chr(c).replace("\\", "backslash")
            f.write("    {" + ", ".join(f"0x{v:04x}" for v in cols) + f"}}, /* {ch} */\n")
        f.write("};\n")

    sheet = Image.new("L", (W * 19, H * 5), 0)
    for i, g in enumerate(rows):
        sheet.paste(g, ((i % 19) * W, (i // 19) * H))
    sheet.resize((sheet.width * 4, sheet.height * 4), Image.NEAREST).save(os.path.join(HERE, "font_preview.png"))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
